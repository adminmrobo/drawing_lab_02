# -*- coding: utf-8 -*-
"""본문 '숫자로 한 번 해 보기'와 퀴즈·평가 점수 검산. python3 build/check_numbers.py"""
import math, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from content_a import P1, P2, P3
from content_b import P4, P5, P6
ok = True
def chk(name, got, want, tol=0.01):
    global ok
    good = abs(got - want) <= tol
    ok &= good
    print(("OK " if good else "XX "), name, round(got, 4), "기대", want)
# 1부 2단계 부피
chk("1-2 t1.5", 16 + 2 * 1.5, 19); chk("1-2 19%", 3 / 16, 0.19, 0.005); chk("1-2 t3", 16 + 2 * 3, 22); chk("1-2 37.5%", 6 / 16, 0.375); chk("1-2 퀴즈", 16 + 2 * 2, 20)
# 2부 1단계 다발, 4단계 나선
chk("2-1 ÷12", 100000 / 12, 8333, 0.5); chk("2-1 ÷40", 100000 / 40, 2500); chk("2-1 36줄", 12 * 3, 36); chk("2-1 퀴즈", 10 * 4, 40)
c = 2 * math.pi * 1.5
chk("2-4 둘레", c, 9.42, 0.005); chk("2-4 한 바퀴", math.sqrt(c**2 + 9), 9.89, 0.005); chk("2-4 5바퀴", 5 * math.sqrt(c**2 + 9), 49.5, 0.06); chk("2-4 배수", 5 * math.sqrt(c**2 + 9) / 15, 3.3, 0.05)
# 3부 1단계 밝기, 2단계 띠, 4단계 윤기 비율
L = lambda r, g, b: 0.299 * r + 0.587 * g + 0.114 * b
chk("3-1 붉은", L(180, 60, 50), 94.7, 0.05); chk("3-1 붉은%", L(180, 60, 50) / 255, 0.37, 0.005)
chk("3-1 갈색", L(170, 125, 85), 133.9, 0.06); chk("3-1 갈색%", L(170, 125, 85) / 255, 0.53, 0.006)
chk("3-1 금발", L(230, 200, 140), 202.1, 0.06); chk("3-1 금발%", L(230, 200, 140) / 255, 0.79, 0.005)
chk("3-1 무게합", 0.299 + 0.587 + 0.114, 1.0)
chk("3-2 60·0", (60 + 0) / 2, 30); chk("3-2 90·0", (90 + 0) / 2, 45); chk("3-2 40·20", (40 + 20) / 2, 30); chk("3-2 퀴즈", (80 + 0) / 2, 40)
chk("3-4 15", 15 / 200, 0.075); chk("3-4 30", 30 / 200, 0.15); chk("3-4 60", 60 / 200, 0.30); chk("3-4 퀴즈", 45 / 300, 0.15)
# 4부 1단계 풍속², 2단계 늦게 따라오기
chk("4-1 2배", 2**2, 4); chk("4-1 3배", 3**2, 9); chk("4-1 퀴즈", 4**2, 16)
chk("4-2 10cm", 10 / 150, 0.07, 0.004); chk("4-2 10cm장", 10 / 150 * 24, 2, 0.5); chk("4-2 30cm", 30 / 150, 0.2); chk("4-2 30cm장", 0.2 * 24, 5, 0.25)
chk("4-2 60cm", 60 / 150, 0.4); chk("4-2 60cm장", 0.4 * 24, 10, 0.5); chk("4-2 퀴즈", 45 / 150, 0.3)
# 5부 2단계 가림 영역, 3단계 가이드
chk("5-2 전체", 512 * 768, 393216); chk("5-2 17.8%", 70000 / 393216, 0.178, 0.001); chk("5-2 30.5%", 120000 / 393216, 0.305, 0.001); chk("5-2 퀴즈", 50000 / (400 * 500), 0.25)
chk("5-3 200×500", 200 * 500, 100000); chk("5-3 400×250", 400 * 250, 100000); chk("5-3 50×2000", 50 * 2000, 100000); chk("5-3 퀴즈", 250 * 400, 100000)
# 퀴즈 정답 번호가 보기 범위 안인지
for P in (P1, P2, P3, P4, P5, P6):
    for s in P["steps"]:
        q = s["quiz"]; good = 0 <= q[2] < len(q[1]); ok &= good
        if not good: print("XX 퀴즈 번호", P["no"], s["id"])
    J = P["judge"]; print("   ", P["no"], "부 평가", sum(J["a"][1]), ":", sum(J["b"][1]), "|", J["result"][0][2][:20])
    # 결과 문장의 'a 대 b'가 실제 합계와 맞는지
    import re
    m = re.search(r"(\d+) 대 (\d+)", J["result"][0][2])
    if m:
        good = int(m.group(1)) == sum(J["a"][1]) and int(m.group(2)) == sum(J["b"][1]); ok &= good
        print(("OK " if good else "XX "), P["no"], "부 점수 문장")
for f in P6["fails"]:
    good = 0 <= f["ans"] < len(f["opts"]); ok &= good
print("전체 통과" if ok else "검산 실패"); sys.exit(0 if ok else 1)
